package net.mokatech.testable;

import net.mokatech.testable.api.Testable;
import net.mokatech.testable.api.TestableInterface;

import javax.annotation.processing.*;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.*;
import javax.lang.model.type.*;
import javax.lang.model.util.ElementFilter;
import javax.lang.model.util.Elements;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;
import java.io.IOException;
import java.io.Writer;
import java.util.*;
import java.util.function.*;
import java.util.stream.*;

@SupportedAnnotationTypes("net.mokatech.testable.api.Testable")
public class TestableAnnotationProcessor extends AbstractProcessor {

    private static final String GENERATED_ANNOTATION = "javax.annotation.processing.Generated";

    /** Classes whose interface has already been generated (a class may be reached both directly and through its package). */
    private final Set<String> processed = new HashSet<>();

    /** Classes postponed to a later round because some of their field types are not resolved yet (e.g. generated by another processor). */
    private final Set<String> deferred = new LinkedHashSet<>();

    private Elements elementUtils;
    private Messager messager;
    private Filer filer;

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        super.init(processingEnv);
        this.elementUtils = processingEnv.getElementUtils();
        this.messager = processingEnv.getMessager();
        this.filer = processingEnv.getFiler();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {


        Set<TypeElement> candidates = new LinkedHashSet<>();
        for (String name : deferred) {
            TypeElement type = processingEnv.getElementUtils().getTypeElement(name);
            if (type != null) {
                candidates.add(type);
            }
        }
        deferred.clear();

        for (Element element : roundEnv.getElementsAnnotatedWith(Testable.class)) {
            if (isSupportedKind(element)) {
                candidates.add((TypeElement) element);
            } else if (element.getKind() == ElementKind.PACKAGE) {
                ElementFilter.typesIn(element.getEnclosedElements()).stream()
                             .filter(this::isSupportedKind)
                             .forEach(candidates::add);
            } else if (element.getKind() == ElementKind.METHOD) {
                // The enclosing class gets an interface, exposing at least this method
                if (!isExposableMethod((ExecutableElement) element)) {
                    messager.printMessage(Diagnostic.Kind.WARNING, "@Testable methods must be private and non-static, method ignored", element);
                } else if (!isSupportedKind(element.getEnclosingElement())) {
                    messager.printMessage(Diagnostic.Kind.WARNING, "@Testable methods are only supported in classes and enums, method ignored", element);
                } else {
                    candidates.add((TypeElement) element.getEnclosingElement());
                }
            } else if (element.getKind() == ElementKind.FIELD) {
                // Same for fields
                if (!isExposableField((VariableElement) element)) {
                    messager.printMessage(Diagnostic.Kind.WARNING, "@Testable fields must be private and non-static, field ignored", element);
                } else if (!isSupportedKind(element.getEnclosingElement())) {
                    messager.printMessage(Diagnostic.Kind.WARNING, "@Testable fields are only supported in classes and enums, field ignored", element);
                } else {
                    candidates.add((TypeElement) element.getEnclosingElement());
                }
            } else {
                messager.printMessage(Diagnostic.Kind.WARNING, "@Testable is only supported on classes, enums, fields, methods and packages", element);
            }
        }

        for (TypeElement candidate : candidates) {
            String name = candidate.getQualifiedName().toString();
            if (processed.contains(name)) {
                continue;
            }
            if (elementUtils.getPackageOf(candidate).isUnnamed()) {
                processed.add(name);
                messager.printMessage(Diagnostic.Kind.WARNING, "@Testable is not supported in the default package, class ignored", candidate);
                continue;
            }
            // Unresolved types may be generated by other processors in later rounds; on the last round, generate with what is resolvable
            if (hasUnresolvedMemberTypes(candidate) && !roundEnv.processingOver()) {
                deferred.add(name);
                continue;
            }
            processed.add(name);
            generateInterface(candidate);
        }
        return true;
    }

    private void generateInterface(TypeElement classElement) {
        PackageElement packageElement = elementUtils.getPackageOf(classElement);
        String packageName = packageElement.getQualifiedName().toString();
        String binaryName = elementUtils.getBinaryName(classElement).toString();
        // Derived from the binary name (Outer$Inner) so that nested classes sharing a simple name get distinct interfaces
        String interfaceName = "Testable" + binaryName.substring(packageName.length() + 1);
        String qualifiedInterfaceName = packageName + "." + interfaceName;

        // Fully testable classes expose all their fields and private methods; other classes only their @Testable ones
        boolean fullyTestable = isFullyTestable(classElement);
        StringBuilder methods = new StringBuilder();
        boolean erased = false;
        for (VariableElement field : ElementFilter.fieldsIn(classElement.getEnclosedElements())) {
            if (!isExposed(field, fullyTestable)) {
                continue;
            }
            TypeMirror fieldType = field.asType();
            if (anyMatch(fieldType, t -> t.getKind() == TypeKind.ERROR)) {
                messager.printMessage(Diagnostic.Kind.WARNING, "Field type could not be resolved, field ignored", field);
                continue;
            }

            // Type variables of an enclosing class (inner classes) cannot be declared on the interface: fall back to the erasure
            if (anyMatch(fieldType, t -> isForeignTypeVariable(t, classElement, null))) {
                fieldType = processingEnv.getTypeUtils().erasure(fieldType);
                erased = true;
            }
            if (anyMatch(fieldType, t -> isInaccessible(t, packageElement))) {
                messager.printMessage(Diagnostic.Kind.NOTE, "Field type is not accessible from the Testable interface, field ignored", field);
                continue;
            }
            // Fields are suffixed with $$ and methods with $, so that a field and a no-arg method sharing a name do not clash
            methods.append("    ").append(print(fieldType)).append(" ").append(field.getSimpleName()).append("$$();\n");
        }

        for (ExecutableElement method : ElementFilter.methodsIn(classElement.getEnclosedElements())) {
            if (!isExposed(method, fullyTestable)) {
                continue;
            }
            String declaration = methodDeclaration(method, classElement, packageElement);
            if (declaration != null) {
                methods.append(declaration);
                erased |= signatureTypes(method).stream().anyMatch(type -> anyMatch(type, t -> isForeignTypeVariable(t, classElement, method)));
            }
        }

        StringBuilder source = new StringBuilder();
        source.append("package ").append(packageName).append(";\n\n");
        if (elementUtils.getTypeElement(GENERATED_ANNOTATION) != null) {
            source.append("@").append(GENERATED_ANNOTATION).append("(\"").append(getClass().getName()).append("\")\n");
        }
        source.append("@").append(TestableInterface.class.getName()).append("(\"").append(binaryName).append("\")\n");
        if (erased) {
            source.append("@SuppressWarnings(\"rawtypes\")\n");
        }
        source.append("public interface ").append(interfaceName).append(typeParameters(classElement.getTypeParameters(), classElement, null, packageElement)).append(" {\n")
              .append(methods)
              .append("}\n");

        try {
            JavaFileObject file = filer.createSourceFile(qualifiedInterfaceName, classElement);
            try (Writer out = file.openWriter()) {
                out.write(source.toString());
            }
            messager.printMessage(Diagnostic.Kind.NOTE, "Generated " + qualifiedInterfaceName, classElement);
        } catch (IOException e) {
            messager.printMessage(Diagnostic.Kind.ERROR, "Error while generating the Testable interface " + qualifiedInterfaceName + ": " + e, classElement);
        }
    }

    // ------------------------------------------------------------------------
    // Methods
    // ------------------------------------------------------------------------

    /** Declares the interface method mirroring a private method, or returns null (with a diagnostic) if it cannot be exposed. */
    private String methodDeclaration(ExecutableElement method, TypeElement classElement, PackageElement packageElement) {
        String name = method.getSimpleName().toString();
        // foo$() would become foo$$(), which the agent reads as the accessor of a field foo
        if (name.endsWith("$")) {
            messager.printMessage(Diagnostic.Kind.WARNING, "Method names ending with $ cannot be told apart from field accessors in the Testable interface, method ignored", method);
            return null;
        }
        if (signatureTypes(method).stream().anyMatch(type -> anyMatch(type, t -> t.getKind() == TypeKind.ERROR))) {
            messager.printMessage(Diagnostic.Kind.WARNING, "Method signature could not be resolved, method ignored", method);
            return null;
        }

        TypeMirror returnType = exposedType(method.getReturnType(), classElement, method);
        List<TypeMirror> parameterTypes = method.getParameters().stream()
                                                .map(parameter -> exposedType(parameter.asType(), classElement, method))
                                                .collect(Collectors.toList());
        if (Stream.concat(Stream.of(returnType), parameterTypes.stream()).anyMatch(type -> anyMatch(type, t -> isInaccessible(t, packageElement)))) {
            messager.printMessage(Diagnostic.Kind.NOTE, "Method signature is not accessible from the Testable interface, method ignored", method);
            return null;
        }
        // The agent finds the private method by its erased parameter types: they must be the same on the interface
        if (parameterTypes.stream().anyMatch(type -> changesErasure(type, classElement, method, packageElement))) {
            messager.printMessage(Diagnostic.Kind.NOTE, "Method parameter types cannot keep their erasure in the Testable interface, method ignored", method);
            return null;
        }

        StringBuilder declaration = new StringBuilder("    ");
        String typeParameters = typeParameters(method.getTypeParameters(), classElement, method, packageElement);
        if (!typeParameters.isEmpty()) {
            declaration.append(typeParameters).append(" ");
        }
        declaration.append(print(returnType)).append(" ").append(name).append("$(");
        for (int i = 0; i < parameterTypes.size(); i++) {
            TypeMirror parameterType = parameterTypes.get(i);
            boolean varArgs = method.isVarArgs() && i == parameterTypes.size() - 1;
            declaration.append(i == 0 ? "" : ", ")
                       .append(varArgs ? print(((ArrayType) parameterType).getComponentType()) + "..." : print(parameterType))
                       .append(" ").append(method.getParameters().get(i).getSimpleName());
        }
        declaration.append(")");

        // Checked exceptions must be declared for the callers to compile: widen the inaccessible ones
        List<String> thrownTypes = method.getThrownTypes().stream()
                                         .map(type -> print(accessibleThrownType(exposedType(type, classElement, method), packageElement)))
                                         .distinct()
                                         .collect(Collectors.toList());
        if (!thrownTypes.isEmpty()) {
            declaration.append(" throws ").append(String.join(", ", thrownTypes));
        }
        return declaration.append(";\n").toString();
    }

    /** Private instance methods are exposed if the class is fully testable, or if they are annotated themselves. */
    private boolean isExposed(ExecutableElement method, boolean fullyTestable) {
        return isExposableMethod(method) && (fullyTestable || method.getAnnotation(Testable.class) != null);
    }

    private boolean isExposableMethod(ExecutableElement method) {
        return method.getModifiers().contains(Modifier.PRIVATE) && !method.getModifiers().contains(Modifier.STATIC);
    }

    /** Private instance fields are exposed if the class is fully testable, or if they are annotated themselves. */
    private boolean isExposed(VariableElement field, boolean fullyTestable) {
        return isExposableField(field) && (fullyTestable || field.getAnnotation(Testable.class) != null);
    }

    /** Non-private members are accessible to the tests of the same package: only private ones need an accessor. */
    private boolean isExposableField(VariableElement field) {
        return field.getModifiers().contains(Modifier.PRIVATE) && !field.getModifiers().contains(Modifier.STATIC);
    }

    /** All the types a method signature is built from: return, parameters, exceptions and type parameter bounds. */
    private List<TypeMirror> signatureTypes(ExecutableElement method) {
        List<TypeMirror> types = new ArrayList<>();
        types.add(method.getReturnType());
        method.getParameters().forEach(parameter -> types.add(parameter.asType()));
        types.addAll(method.getThrownTypes());
        method.getTypeParameters().forEach(parameter -> types.addAll(parameter.getBounds()));
        return types;
    }

    /** Type variables of an enclosing class (inner classes) cannot be declared on the interface: fall back to the erasure. */
    private TypeMirror exposedType(TypeMirror type, TypeElement classElement, ExecutableElement method) {
        return anyMatch(type, t -> isForeignTypeVariable(t, classElement, method)) ? processingEnv.getTypeUtils().erasure(type) : type;
    }

    /** Whether the type is a type variable (or an array of) whose bounds are dropped on the interface, which changes its erasure. */
    private boolean changesErasure(TypeMirror type, TypeElement classElement, ExecutableElement method, PackageElement packageElement) {
        while (type.getKind() == TypeKind.ARRAY) {
            type = ((ArrayType) type).getComponentType();
        }
        if (type.getKind() != TypeKind.TYPEVAR) {
            return false;
        }
        TypeParameterElement parameter = (TypeParameterElement) ((TypeVariable) type).asElement();
        return !boundsExpressible(parameter, classElement, method, packageElement)
               && !isJavaLangObject(processingEnv.getTypeUtils().erasure(type));
    }

    /** The type itself if accessible from the interface, otherwise its closest accessible superclass (Exception at worst). */
    private TypeMirror accessibleThrownType(TypeMirror type, PackageElement packageElement) {
        while (type.getKind() == TypeKind.DECLARED && isInaccessible(type, packageElement)) {
            type = ((TypeElement) ((DeclaredType) type).asElement()).getSuperclass();
        }
        return type;
    }

    // ------------------------------------------------------------------------
    // Type parameters
    // ------------------------------------------------------------------------

    /** Re-declares the class' (or method's) type parameters on the interface, so that generic types can be expressed. */
    private String typeParameters(List<? extends TypeParameterElement> parameters, TypeElement classElement, ExecutableElement method, PackageElement packageElement) {
        if (parameters.isEmpty()) {
            return "";
        }
        return parameters.stream()
                         .map(parameter -> typeParameter(parameter, classElement, method, packageElement))
                         .collect(Collectors.joining(", ", "<", ">"));
    }

    private String typeParameter(TypeParameterElement parameter, TypeElement classElement, ExecutableElement method, PackageElement packageElement) {
        String name = parameter.getSimpleName().toString();
        List<? extends TypeMirror> bounds = bounds(parameter);

        // Bounds are only a convenience for the caller: drop them if the interface cannot express them
        if (bounds.isEmpty() || !boundsExpressible(parameter, classElement, method, packageElement)) {
            return name;
        }
        return name + bounds.stream().map(this::print).collect(Collectors.joining(" & ", " extends ", ""));
    }

    private List<? extends TypeMirror> bounds(TypeParameterElement parameter) {
        return parameter.getBounds().stream()
                        .filter(bound -> !isJavaLangObject(bound))
                        .collect(Collectors.toList());
    }

    private boolean boundsExpressible(TypeParameterElement parameter, TypeElement classElement, ExecutableElement method, PackageElement packageElement) {
        return bounds(parameter).stream()
                                .noneMatch(bound -> anyMatch(bound, t -> t.getKind() == TypeKind.ERROR || isForeignTypeVariable(t, classElement, method) || isInaccessible(t, packageElement)));
    }

    // ------------------------------------------------------------------------
    // Type inspection
    // ------------------------------------------------------------------------

    private boolean isSupportedKind(Element element) {
        return element.getKind() == ElementKind.CLASS || element.getKind() == ElementKind.ENUM;
    }

    /** Directly annotated, or top-level in an annotated package: all fields and private methods are exposed. */
    private boolean isFullyTestable(TypeElement classElement) {
        return classElement.getAnnotation(Testable.class) != null
               || (classElement.getNestingKind() == NestingKind.TOP_LEVEL && elementUtils.getPackageOf(classElement).getAnnotation(Testable.class) != null);
    }

    private boolean hasUnresolvedMemberTypes(TypeElement classElement) {
        Stream<TypeMirror> fieldTypes = ElementFilter.fieldsIn(classElement.getEnclosedElements()).stream()
                                                     .filter(this::isExposableField)
                                                     .map(VariableElement::asType);
        Stream<TypeMirror> methodTypes = ElementFilter.methodsIn(classElement.getEnclosedElements()).stream()
                                                      .filter(this::isExposableMethod)
                                                      .flatMap(method -> signatureTypes(method).stream());
        return Stream.concat(fieldTypes, methodTypes).anyMatch(type -> anyMatch(type, t -> t.getKind() == TypeKind.ERROR));
    }

    /** Whether the type, or any type it is built from (array component, type arguments, wildcard bounds...), matches. */
    private boolean anyMatch(TypeMirror type, Predicate<TypeMirror> predicate) {
        if (predicate.test(type)) {
            return true;
        }
        switch (type.getKind()) {
            case ARRAY:
                return anyMatch(((ArrayType) type).getComponentType(), predicate);
            case DECLARED:
                DeclaredType declaredType = (DeclaredType) type;
                return anyMatch(declaredType.getEnclosingType(), predicate)
                       || declaredType.getTypeArguments().stream().anyMatch(argument -> anyMatch(argument, predicate));
            case WILDCARD:
                WildcardType wildcardType = (WildcardType) type;
                return (wildcardType.getExtendsBound() != null && anyMatch(wildcardType.getExtendsBound(), predicate))
                       || (wildcardType.getSuperBound() != null && anyMatch(wildcardType.getSuperBound(), predicate));
            default:
                return false;
        }
    }

    /** Whether the type is a type variable declared neither by the class nor by the given method (which may be null). */
    private boolean isForeignTypeVariable(TypeMirror type, TypeElement classElement, ExecutableElement method) {
        if (type.getKind() != TypeKind.TYPEVAR) {
            return false;
        }
        Element genericElement = ((TypeParameterElement) ((TypeVariable) type).asElement()).getGenericElement();
        return !genericElement.equals(classElement) && !genericElement.equals(method);
    }

    /** Whether the type cannot be referenced from an interface generated in the given package (private, local, or non-public from another package). */
    private boolean isInaccessible(TypeMirror type, PackageElement packageElement) {
        if (type.getKind() != TypeKind.DECLARED) {
            return false;
        }
        TypeElement typeElement = (TypeElement) ((DeclaredType) type).asElement();
        for (Element element = typeElement; element instanceof TypeElement; element = element.getEnclosingElement()) {
            NestingKind nestingKind = ((TypeElement) element).getNestingKind();
            Set<Modifier> modifiers = element.getModifiers();
            if (nestingKind == NestingKind.LOCAL || nestingKind == NestingKind.ANONYMOUS || modifiers.contains(Modifier.PRIVATE)) {
                return true;
            }
            if (!modifiers.contains(Modifier.PUBLIC) && !processingEnv.getElementUtils().getPackageOf(element).equals(packageElement)) {
                return true;
            }
        }
        return false;
    }

    private boolean isJavaLangObject(TypeMirror type) {
        return type.getKind() == TypeKind.DECLARED
               && ((TypeElement) ((DeclaredType) type).asElement()).getQualifiedName().contentEquals("java.lang.Object");
    }

    // ------------------------------------------------------------------------
    // Type printing
    // ------------------------------------------------------------------------

    /** Prints a type as valid source code, using fully qualified names and without type annotations. */
    private String print(TypeMirror type) {
        switch (type.getKind()) {
            case ARRAY:
                return print(((ArrayType) type).getComponentType()) + "[]";
            case DECLARED:
                DeclaredType declaredType = (DeclaredType) type;
                TypeElement typeElement = (TypeElement) declaredType.asElement();
                TypeMirror enclosingType = declaredType.getEnclosingType();
                String name = enclosingType.getKind() == TypeKind.DECLARED && !((DeclaredType) enclosingType).getTypeArguments().isEmpty()
                        ? print(enclosingType) + "." + typeElement.getSimpleName()
                        : typeElement.getQualifiedName().toString();
                List<? extends TypeMirror> arguments = declaredType.getTypeArguments();
                return arguments.isEmpty() ? name : name + arguments.stream().map(this::print).collect(Collectors.joining(", ", "<", ">"));
            case TYPEVAR:
                return ((TypeVariable) type).asElement().getSimpleName().toString();
            case WILDCARD:
                WildcardType wildcardType = (WildcardType) type;
                if (wildcardType.getExtendsBound() != null) {
                    return "? extends " + print(wildcardType.getExtendsBound());
                }
                if (wildcardType.getSuperBound() != null) {
                    return "? super " + print(wildcardType.getSuperBound());
                }
                return "?";
            case VOID:
                return "void";
            default:
                if (type.getKind().isPrimitive()) {
                    return type.getKind().name().toLowerCase(Locale.ROOT);
                }
                throw new IllegalArgumentException("Unsupported type: " + type);
        }
    }

}
