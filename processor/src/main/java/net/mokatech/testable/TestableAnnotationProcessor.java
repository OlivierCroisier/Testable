package net.mokatech.testable;

import net.mokatech.testable.api.Testable;
import net.mokatech.testable.api.TestableInterface;

import javax.annotation.processing.*;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.*;
import javax.lang.model.type.*;
import javax.lang.model.util.ElementFilter;
import javax.lang.model.util.Elements;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;
import java.io.IOException;
import java.io.Writer;
import java.util.*;
import java.util.function.*;
import java.util.stream.*;

@SupportedAnnotationTypes("net.mokatech.testable.api.Testable")
public class TestableAnnotationProcessor extends AbstractProcessor {

    private static final String GENERATED_ANNOTATION = "javax.annotation.processing.Generated";

    /** Classes whose interface has already been generated (a class may be reached both directly and through its package). */
    private final Set<String> processed = new HashSet<>();

    /** Classes postponed to a later round because some of their field types are not resolved yet (e.g. generated by another processor). */
    private final Set<String> deferred = new LinkedHashSet<>();

    private Elements elementUtils;
    private Messager messager;
    private Filer filer;

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        super.init(processingEnv);
        this.elementUtils = processingEnv.getElementUtils();
        this.messager = processingEnv.getMessager();
        this.filer = processingEnv.getFiler();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {


        Set<TypeElement> candidates = new LinkedHashSet<>();
        for (String name : deferred) {
            TypeElement type = processingEnv.getElementUtils().getTypeElement(name);
            if (type != null) {
                candidates.add(type);
            }
        }
        deferred.clear();

        for (Element element : roundEnv.getElementsAnnotatedWith(Testable.class)) {
            if (isSupportedKind(element)) {
                candidates.add((TypeElement) element);
            } else if (element.getKind() == ElementKind.PACKAGE) {
                ElementFilter.typesIn(element.getEnclosedElements()).stream()
                             .filter(this::isSupportedKind)
                             .forEach(candidates::add);
            } else {
                messager.printMessage(Diagnostic.Kind.WARNING, "@Testable is only supported on classes, enums and packages", element);
            }
        }

        for (TypeElement candidate : candidates) {
            String name = candidate.getQualifiedName().toString();
            if (processed.contains(name)) {
                continue;
            }
            if (elementUtils.getPackageOf(candidate).isUnnamed()) {
                processed.add(name);
                messager.printMessage(Diagnostic.Kind.WARNING, "@Testable is not supported in the default package, class ignored", candidate);
                continue;
            }
            // Unresolved types may be generated by other processors in later rounds; on the last round, generate with what is resolvable
            if (hasUnresolvedFieldTypes(candidate) && !roundEnv.processingOver()) {
                deferred.add(name);
                continue;
            }
            processed.add(name);
            generateInterface(candidate);
        }
        return true;
    }

    private void generateInterface(TypeElement classElement) {
        PackageElement packageElement = elementUtils.getPackageOf(classElement);
        String packageName = packageElement.getQualifiedName().toString();
        String binaryName = elementUtils.getBinaryName(classElement).toString();
        // Derived from the binary name (Outer$Inner) so that nested classes sharing a simple name get distinct interfaces
        String interfaceName = "Testable" + binaryName.substring(packageName.length() + 1);
        String qualifiedInterfaceName = packageName + "." + interfaceName;

        StringBuilder methods = new StringBuilder();
        boolean erased = false;
        for (VariableElement field : ElementFilter.fieldsIn(classElement.getEnclosedElements())) {
            if (field.getModifiers().contains(Modifier.STATIC)) {
                continue;
            }
            TypeMirror fieldType = field.asType();
            if (anyMatch(fieldType, t -> t.getKind() == TypeKind.ERROR)) {
                messager.printMessage(Diagnostic.Kind.WARNING, "Field type could not be resolved, field ignored", field);
                continue;
            }

            // Type variables of an enclosing class (inner classes) cannot be declared on the interface: fall back to the erasure
            if (anyMatch(fieldType, t -> isForeignTypeVariable(t, classElement))) {
                fieldType = processingEnv.getTypeUtils().erasure(fieldType);
                erased = true;
            }
            if (anyMatch(fieldType, t -> isInaccessible(t, packageElement))) {
                messager.printMessage(Diagnostic.Kind.NOTE, "Field type is not accessible from the Testable interface, field ignored", field);
                continue;
            }
            methods.append("    ").append(print(fieldType)).append(" ").append(field.getSimpleName()).append("$();\n");
        }

        StringBuilder source = new StringBuilder();
        source.append("package ").append(packageName).append(";\n\n");
        if (elementUtils.getTypeElement(GENERATED_ANNOTATION) != null) {
            source.append("@").append(GENERATED_ANNOTATION).append("(\"").append(getClass().getName()).append("\")\n");
        }
        source.append("@").append(TestableInterface.class.getName()).append("(\"").append(binaryName).append("\")\n");
        if (erased) {
            source.append("@SuppressWarnings(\"rawtypes\")\n");
        }
        source.append("public interface ").append(interfaceName).append(typeParameters(classElement, packageElement)).append(" {\n")
              .append(methods)
              .append("}\n");

        try {
            JavaFileObject file = filer.createSourceFile(qualifiedInterfaceName, classElement);
            try (Writer out = file.openWriter()) {
                out.write(source.toString());
            }
            messager.printMessage(Diagnostic.Kind.NOTE, "Generated " + qualifiedInterfaceName, classElement);
        } catch (IOException e) {
            messager.printMessage(Diagnostic.Kind.ERROR, "Error while generating the Testable interface " + qualifiedInterfaceName + ": " + e, classElement);
        }
    }

    // ------------------------------------------------------------------------
    // Type parameters
    // ------------------------------------------------------------------------

    /** Re-declares the class' type parameters on the interface, so that generic field types can be expressed. */
    private String typeParameters(TypeElement classElement, PackageElement packageElement) {
        List<? extends TypeParameterElement> parameters = classElement.getTypeParameters();
        if (parameters.isEmpty()) {
            return "";
        }
        return parameters.stream()
                         .map(parameter -> typeParameter(parameter, classElement, packageElement))
                         .collect(Collectors.joining(", ", "<", ">"));
    }

    private String typeParameter(TypeParameterElement parameter, TypeElement classElement, PackageElement packageElement) {
        String name = parameter.getSimpleName().toString();
        List<? extends TypeMirror> bounds = parameter.getBounds().stream()
                                                     .filter(bound -> !isJavaLangObject(bound))
                                                     .collect(Collectors.toList());

        // Bounds are only a convenience for the caller: drop them if the interface cannot express them
        boolean expressible = bounds.stream().noneMatch(bound -> anyMatch(bound, t -> t.getKind() == TypeKind.ERROR || isForeignTypeVariable(t, classElement) || isInaccessible(t, packageElement)));
        if (bounds.isEmpty() || !expressible) {
            return name;
        }
        return name + bounds.stream().map(this::print).collect(Collectors.joining(" & ", " extends ", ""));
    }

    // ------------------------------------------------------------------------
    // Type inspection
    // ------------------------------------------------------------------------

    private boolean isSupportedKind(Element element) {
        return element.getKind() == ElementKind.CLASS || element.getKind() == ElementKind.ENUM;
    }

    private boolean hasUnresolvedFieldTypes(TypeElement classElement) {
        return ElementFilter.fieldsIn(classElement.getEnclosedElements()).stream()
                            .anyMatch(field -> anyMatch(field.asType(), t -> t.getKind() == TypeKind.ERROR));
    }

    /** Whether the type, or any type it is built from (array component, type arguments, wildcard bounds...), matches. */
    private boolean anyMatch(TypeMirror type, Predicate<TypeMirror> predicate) {
        if (predicate.test(type)) {
            return true;
        }
        switch (type.getKind()) {
            case ARRAY:
                return anyMatch(((ArrayType) type).getComponentType(), predicate);
            case DECLARED:
                DeclaredType declaredType = (DeclaredType) type;
                return anyMatch(declaredType.getEnclosingType(), predicate)
                       || declaredType.getTypeArguments().stream().anyMatch(argument -> anyMatch(argument, predicate));
            case WILDCARD:
                WildcardType wildcardType = (WildcardType) type;
                return (wildcardType.getExtendsBound() != null && anyMatch(wildcardType.getExtendsBound(), predicate))
                       || (wildcardType.getSuperBound() != null && anyMatch(wildcardType.getSuperBound(), predicate));
            default:
                return false;
        }
    }

    private boolean isForeignTypeVariable(TypeMirror type, TypeElement classElement) {
        return type.getKind() == TypeKind.TYPEVAR
               && !((TypeParameterElement) ((TypeVariable) type).asElement()).getGenericElement().equals(classElement);
    }

    /** Whether the type cannot be referenced from an interface generated in the given package (private, local, or non-public from another package). */
    private boolean isInaccessible(TypeMirror type, PackageElement packageElement) {
        if (type.getKind() != TypeKind.DECLARED) {
            return false;
        }
        TypeElement typeElement = (TypeElement) ((DeclaredType) type).asElement();
        for (Element element = typeElement; element instanceof TypeElement; element = element.getEnclosingElement()) {
            NestingKind nestingKind = ((TypeElement) element).getNestingKind();
            Set<Modifier> modifiers = element.getModifiers();
            if (nestingKind == NestingKind.LOCAL || nestingKind == NestingKind.ANONYMOUS || modifiers.contains(Modifier.PRIVATE)) {
                return true;
            }
            if (!modifiers.contains(Modifier.PUBLIC) && !processingEnv.getElementUtils().getPackageOf(element).equals(packageElement)) {
                return true;
            }
        }
        return false;
    }

    private boolean isJavaLangObject(TypeMirror type) {
        return type.getKind() == TypeKind.DECLARED
               && ((TypeElement) ((DeclaredType) type).asElement()).getQualifiedName().contentEquals("java.lang.Object");
    }

    // ------------------------------------------------------------------------
    // Type printing
    // ------------------------------------------------------------------------

    /** Prints a type as valid source code, using fully qualified names and without type annotations. */
    private String print(TypeMirror type) {
        switch (type.getKind()) {
            case ARRAY:
                return print(((ArrayType) type).getComponentType()) + "[]";
            case DECLARED:
                DeclaredType declaredType = (DeclaredType) type;
                TypeElement typeElement = (TypeElement) declaredType.asElement();
                TypeMirror enclosingType = declaredType.getEnclosingType();
                String name = enclosingType.getKind() == TypeKind.DECLARED && !((DeclaredType) enclosingType).getTypeArguments().isEmpty()
                        ? print(enclosingType) + "." + typeElement.getSimpleName()
                        : typeElement.getQualifiedName().toString();
                List<? extends TypeMirror> arguments = declaredType.getTypeArguments();
                return arguments.isEmpty() ? name : name + arguments.stream().map(this::print).collect(Collectors.joining(", ", "<", ">"));
            case TYPEVAR:
                return ((TypeVariable) type).asElement().getSimpleName().toString();
            case WILDCARD:
                WildcardType wildcardType = (WildcardType) type;
                if (wildcardType.getExtendsBound() != null) {
                    return "? extends " + print(wildcardType.getExtendsBound());
                }
                if (wildcardType.getSuperBound() != null) {
                    return "? super " + print(wildcardType.getSuperBound());
                }
                return "?";
            default:
                if (type.getKind().isPrimitive()) {
                    return type.getKind().name().toLowerCase(Locale.ROOT);
                }
                throw new IllegalArgumentException("Unsupported field type: " + type);
        }
    }

}
